//Addition of Two Numbers
#include<iostream>
using namespace std;
main()
{ int a,b;
  cout<<"Enter a,b values:";
  cin>>a>>b;
  cout<<"\nAddition of a and b is : "<<a+b<<endl;
  cout<<"Subtraction of a and b is: "<<a-b<<endl;
  cout<<"Multiplication of a and b is : "<<a*b;
  cout<<"\nDivision(/) of a and b is : "<<a/b;
  cout<<"\nDivision(%) of a and b is : "<<a%b;
}
